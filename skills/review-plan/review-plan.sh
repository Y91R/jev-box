#!/usr/bin/env bash
# Прогоняет план реализации через стороннего агента codex и печатает ревью в stdout.
# Это ФОЛБЭК на headless `codex exec --sandbox read-only`: если доступен peer-транспорт
# (Codex в правой панели agterm), скрипт выходит с кодом 4 — там ревью ведётся диалогом
# через peer-chat, без файлов.
# Аргумент $1 — путь к файлу плана. Без аргумента план читается со stdin.
# Codex в репозитории ничего не меняет; правки по итогам решает пользователь.

set -uo pipefail

root="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"

# Peer-транспорт (Codex в правой панели agterm) — общение с ним идёт только диалогом через
# peer-chat, без файлов обмена, поэтому этот скрипт в таком режиме не работает.
if bash "$HOME/.claude/scripts/peer-available.sh" --cwd "$root" --quiet; then
  cat >&2 <<'PEER'
peer-транспорт доступен (Codex в правой панели, тот же checkout) — этот скрипт не нужен.
Отправь задачу Codex диалогом через ~/.local/bin/peer-chat.py (скилл peer-chat), файлы он читает сам,
ответ придёт отдельным промптом «Chat from Codex:». Нужен headless — запусти с PEER_REVIEW=0.
PEER
  exit 4
fi

umask 077
plan_arg="${1:-}"
cleanup_plan=0
if [ -n "$plan_arg" ]; then
  [ -f "$plan_arg" ] || { echo "файл плана не найден: $plan_arg"; exit 0; }
  plan_file="$(cd "$(dirname "$plan_arg")" && pwd)/$(basename "$plan_arg")"
else
  plan_file="$(mktemp "${TMPDIR:-/tmp}/codex-plan-XXXXXX.md")"
  cleanup_plan=1
  cat > "$plan_file"
  [ -s "$plan_file" ] || { echo "план пуст — укажи путь к файлу плана или передай план на stdin"; rm -f "$plan_file"; exit 0; }
fi

# BSD mktemp подставляет случайные символы, только если XXXXXX в конце шаблона,
# поэтому уникальный каталог, а имена файлов внутри — фиксированные. Каталог остаётся:
# в нём сырой ответ codex (путь печатается в заголовке блока).
work="$(mktemp -d "${TMPDIR:-/tmp}/codex-plan-XXXXXX")"
prompt_file="$work/prompt.txt"
trap '[ "$cleanup_plan" = 1 ] && rm -f "$plan_file"' EXIT

prompt="Ты — сторонний ревьюер плана реализации. Прочитай план в файле ${plan_file}. Открывай файлы, на которые ссылается план, чтобы проверять факты, а не догадки. Верни на русском ТОЛЬКО блокеры — проблемы, из-за которых план при реализации сломается, даст неверный/небезопасный результат или упускает существенный шаг, меняющий подход. Правила: (1) каждый пункт конкретен — что именно не так и где в плане, с фактом, а не догадкой; (2) НЕ пиши минорщину, придирки к стилю/формулировкам/именованию, микрооптимизации, гипотетику без доказательств ('возможно нет флага', 'может не быть утилиты'); (3) НЕ переписывай как проблему то, что план уже осознанно принял (трейд-оффы, out of scope); (4) без повторов и без ревью markdown-оформления; (5) максимум 5 пунктов, по убыванию важности. Если блокеров нет — ответь одной строкой: 'Блокеров нет, план готов к реализации.' Не выдумывай проблемы, чтобы заполнить ответ. Ничего в репозитории не меняй."

# JEV_HINTS — абзац подсказок Jev от скилла jev-box:review-plan, дописывается к промпту как есть.
[ -n "${JEV_HINTS:-}" ] && prompt="${prompt} ${JEV_HINTS}"
printf '%s\n' "$prompt" >"$prompt_file"
bash "$HOME/.claude/scripts/external-review.sh" "$prompt_file" --cwd "$root" --timeout 1200 --out "$work/codex.out"
